import { readlink, rm } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import type { Diagnostic } from '../../core/diagnostics.ts';
import {
  backupPath,
  lstatOrNull,
  readTextFile,
  replaceSymlink,
  writeFileAtomic,
} from '../../core/fs-atomic.ts';
import { sha256 } from '../../core/hash.ts';
import { assertParentInsideRoot, relativeLink } from '../../core/paths.ts';
import type { GeneratedTarget, ProjectPaths } from '../../model/types.ts';

export type InstructionMode = 'symlink' | 'generated' | 'disabled';

export type InstructionAction =
  | 'none'
  | 'create'
  | 'repair'
  | 'remove'
  | 'backup-and-repair'
  | 'backup-and-remove';

export interface InstructionPlan {
  action: InstructionAction;
  mode: InstructionMode;
  path: '.claude/CLAUDE.md';
  sha256?: string;
  conflict?: Diagnostic;
  /** Absolute authored instruction source used to build the symlink. */
  source?: string;
  /** Expected generated shim content. */
  content?: string;
}

export interface PlanInstructionsInput {
  root: string;
  paths: ProjectPaths;
  mode: InstructionMode;
  generated?: GeneratedTarget;
  fix?: boolean;
}

const TARGET = '.claude/CLAUDE.md' as const;

export function renderClaudeMdShim(importPath = '../AGENTS.md'): string {
  return '<!-- Generated by DAB from AGENTS.md. Do not edit. Run `dab normalize` to regenerate. -->\n'
    + `@${importPath}\n`;
}

function instructionTarget(root: string): string {
  return join(root, '.claude', 'CLAUDE.md');
}

function rootClaudeConflict(): Diagnostic {
  return {
    code: 'claude-md.unmanaged',
    severity: 'error',
    message: 'root CLAUDE.md is user-owned and blocks DAB instructions',
    file: 'CLAUDE.md',
    hint: 'Merge its content into AGENTS.md and remove the file.',
  };
}

function unmanaged(message: string): Diagnostic {
  return {
    code: 'claude-md.unmanaged',
    severity: 'error',
    message,
    file: TARGET,
    hint: 'Merge the file content into AGENTS.md, remove the unmanaged CLAUDE.md, then run dab normalize.',
  };
}

async function resolvesTo(target: string, source: string): Promise<boolean> {
  try {
    const raw = await readlink(target);
    return resolve(dirname(target), raw) === resolve(source);
  } catch {
    return false;
  }
}

async function sourceSha256(source: string): Promise<string | undefined> {
  if ((await lstatOrNull(source)) === null) {
    return undefined;
  }
  return sha256(await readTextFile(source));
}

export async function planInstructions(
  input: PlanInstructionsInput,
): Promise<InstructionPlan> {
  const { root, paths, mode, generated, fix } = input;
  const target = instructionTarget(root);
  const source = paths.instructions;

  if ((await lstatOrNull(join(root, 'CLAUDE.md'))) !== null) {
    return { action: 'none', mode, path: TARGET, conflict: rootClaudeConflict() };
  }

  const content = mode === 'disabled'
    ? undefined
    : renderClaudeMdShim(relativeLink(target, source));
  const digest = mode === 'symlink'
    ? await sourceSha256(source)
    : content === undefined
      ? undefined
      : sha256(content);
  const base: InstructionPlan = {
    action: 'none',
    mode,
    path: TARGET,
    source,
    ...(digest === undefined ? {} : { sha256: digest }),
    ...(content === undefined ? {} : { content }),
  };
  const actual = await lstatOrNull(target);
  const managed = generated?.instructions !== undefined
    && generated?.instructions !== null;

  if (mode === 'disabled') {
    if (actual === null) {
      return base;
    }
    if (managed) {
      return { ...base, action: 'remove' };
    }
    return {
      ...base,
      action: fix === true ? 'backup-and-remove' : 'none',
      conflict: unmanaged('unmanaged .claude/CLAUDE.md exists while instructions are disabled'),
    };
  }

  if (mode === 'symlink') {
    if (actual === null) {
      return { ...base, action: 'create' };
    }
    if (actual.isSymbolicLink()) {
      if (await resolvesTo(target, source)) {
        return base;
      }
      if (managed) {
        return { ...base, action: 'repair' };
      }
      return {
        ...base,
        action: fix === true ? 'backup-and-repair' : 'none',
        conflict: unmanaged('.claude/CLAUDE.md is an unmanaged symlink'),
      };
    }
    if (actual.isFile()) {
      const existing = await readTextFile(target);
      if (managed && existing === content) {
        return { ...base, action: 'repair' };
      }
    }
    return {
      ...base,
      action: fix === true ? 'backup-and-repair' : 'none',
      conflict: unmanaged('.claude/CLAUDE.md exists but is not DAB-managed'),
    };
  }

  if (actual === null) {
    return { ...base, action: 'create' };
  }
  if (actual.isFile()) {
    const existing = await readTextFile(target);
    if (existing === content) {
      return base;
    }
    if (managed) {
      return { ...base, action: 'repair' };
    }
  } else if (actual.isSymbolicLink() && managed) {
    return { ...base, action: 'repair' };
  }
  return {
    ...base,
    action: fix === true ? 'backup-and-repair' : 'none',
    conflict: unmanaged('.claude/CLAUDE.md exists but is not DAB-managed'),
  };
}

export async function applyInstructions(
  root: string,
  plan: InstructionPlan,
  backupRoot?: string,
): Promise<string[]> {
  if (plan.action === 'none') {
    return [];
  }
  await assertParentInsideRoot(root, TARGET);
  const target = instructionTarget(root);
  const info = await lstatOrNull(target);
  const backups: string[] = [];

  if (plan.action === 'backup-and-repair' || plan.action === 'backup-and-remove') {
    if (backupRoot === undefined) {
      throw new Error('backupRoot is required for instruction backup actions');
    }
    backups.push(await backupPath(root, TARGET, backupRoot));
    await rm(target, { recursive: true, force: true });
  }

  switch (plan.action) {
    case 'remove':
    case 'backup-and-remove':
      await rm(target, { recursive: true, force: true });
      break;
    case 'create':
    case 'repair':
    case 'backup-and-repair':
      if (plan.mode === 'symlink') {
        if (plan.source === undefined) {
          throw new Error('instruction source is required for symlink instructions');
        }
        if (info !== null && !info.isSymbolicLink()) {
          await rm(target, { recursive: true, force: true });
        }
        await replaceSymlink(target, relativeLink(target, plan.source));
      } else if (plan.mode === 'generated') {
        if (plan.content === undefined) {
          throw new Error('instruction content is required for generated instructions');
        }
        if (info !== null && !info.isFile()) {
          await rm(target, { recursive: true, force: true });
        }
        await writeFileAtomic(target, plan.content);
      } else {
        throw new Error('cannot materialize disabled instructions');
      }
      break;
  }

  return backups;
}

export async function inspectInstructionTarget(
  root: string,
  paths: ProjectPaths,
  expectedMode: InstructionMode,
  generated?: GeneratedTarget,
): Promise<Diagnostic | undefined> {
  const target = instructionTarget(root);
  const actual = await lstatOrNull(target);
  if (actual === null) {
    return undefined;
  }
  if (generated?.instructions !== undefined && generated?.instructions !== null) {
    return undefined;
  }
  if (expectedMode === 'symlink') {
    if (actual.isSymbolicLink() && await resolvesTo(target, paths.instructions)) {
      return undefined;
    }
  } else if (expectedMode === 'generated' && actual.isFile()) {
    const expected = renderClaudeMdShim(relativeLink(target, paths.instructions));
    if ((await readTextFile(target)) === expected) {
      return undefined;
    }
  }

  return {
    code: 'claude-md.unmanaged',
    severity: 'error',
    message: 'existing .claude/CLAUDE.md is not DAB-managed',
    file: TARGET,
    hint: 'Normalize can back it up and replace it after review.',
  };
}
