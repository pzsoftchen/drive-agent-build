#!/usr/bin/env node
import { fileURLToPath } from 'node:url';
import { readFileSync, realpathSync } from 'node:fs';
import { homedir } from 'node:os';
import { createInterface } from 'node:readline/promises';
import type { CommandRunner } from './core/command.ts';
import { DabError, UsageError } from './core/errors.ts';
import { ExitCode } from './core/exit-codes.ts';
import { contractJson } from './core/json.ts';
import { runDetect } from './commands/detect.ts';
import { runInit } from './commands/init.ts';
import { runNormalize } from './commands/normalize.ts';
import { runPolicyExplain } from './commands/policy-explain.ts';
import { TARGET_PROVIDERS } from './model/schemas.ts';
import type { TargetProvider } from './model/types.ts';

function readProgramVersion(): string {
  const parsed: unknown = JSON.parse(
    readFileSync(new URL('../package.json', import.meta.url), 'utf8'),
  );
  if (
    typeof parsed !== 'object'
    || parsed === null
    || typeof (parsed as { version?: unknown }).version !== 'string'
  ) {
    throw new Error('package.json must declare a string version');
  }
  return (parsed as { version: string }).version;
}

export const PROGRAM_VERSION = readProgramVersion();

export interface CliContext {
  cwd: string;
  stdout: (value: string) => void;
  stderr: (value: string) => void;
  env: NodeJS.ProcessEnv;
  confirm?: (question: string) => Promise<boolean>;
  runner?: CommandRunner;
}

const HELP = `dab ${PROGRAM_VERSION} - Drive Agent as Builder

Usage:
  dab init [path] [--profile feature] [--ai] [--dry-run] [--json]
  dab detect [--json]
  dab normalize [--dry-run] [--fix] [--json]
  dab policy explain [--agent <name>] [--target <provider>] [--json]
  dab --help
  dab --version

Authored source lives in AGENTS.md and .agents/. Claude Code outputs under
.claude/ are generated by "dab normalize" and must not be edited by hand.
`;

function takeOption(args: string[], name: string): string | undefined {
  const index = args.indexOf(name);
  if (index === -1) {
    return undefined;
  }
  const value = args[index + 1];
  if (value === undefined || value.startsWith('-')) {
    throw new UsageError(`missing value for ${name}`, 'usage.missing-option-value');
  }
  return value;
}

function rejectUnknownOptions(args: string[], allowedFlags: string[]): void {
  for (const arg of args) {
    if (arg.startsWith('-') && !allowedFlags.includes(arg)) {
      throw new UsageError(`unknown option: ${arg}`, 'usage.unknown-option');
    }
  }
}

interface InitArguments {
  path?: string;
  profile: 'feature';
  ai: boolean;
  dryRun: boolean;
}

function parseInitArgs(rest: string[]): InitArguments {
  let profile = 'feature';
  let ai = false;
  let dryRun = false;
  let targetPath: string | undefined;

  for (let index = 0; index < rest.length; index += 1) {
    const arg = rest[index] ?? '';
    if (arg === '--ai') {
      ai = true;
      continue;
    }
    if (arg === '--dry-run') {
      dryRun = true;
      continue;
    }
    if (arg === '--profile') {
      const value = rest[index + 1];
      if (value === undefined || value.startsWith('-')) {
        throw new UsageError('missing value for --profile', 'usage.missing-option-value');
      }
      profile = value;
      index += 1;
      continue;
    }
    if (arg.startsWith('-')) {
      throw new UsageError(`unknown option: ${arg}`, 'usage.unknown-option');
    }
    if (targetPath !== undefined) {
      throw new UsageError('init accepts at most one path', 'usage.too-many-paths');
    }
    targetPath = arg;
  }

  if (profile !== 'feature') {
    throw new UsageError(
      `unsupported profile: ${profile}; v0.1 supports: feature`,
      'usage.invalid-profile',
    );
  }
  return {
    ...(targetPath === undefined ? {} : { path: targetPath }),
    profile: 'feature',
    ai,
    dryRun,
  };
}

async function promptConfirm(question: string): Promise<boolean> {
  const readline = createInterface({ input: process.stdin, output: process.stdout });
  try {
    const answer = await readline.question(question);
    return /^y(es)?$/i.test(answer.trim());
  } finally {
    readline.close();
  }
}

async function dispatchInit(
  rest: string[],
  ctx: CliContext,
  json: boolean,
): Promise<number> {
  const parsed = parseInitArgs(rest);
  return runInit(
    {
      cwd: ctx.cwd,
      home: homedir(),
      ...(parsed.path === undefined ? {} : { path: parsed.path }),
      profile: parsed.profile,
      ai: parsed.ai,
      dryRun: parsed.dryRun,
      json,
      ...(parsed.ai && !parsed.dryRun && process.stdin.isTTY ? { confirm: promptConfirm } : {}),
      ...(ctx.runner === undefined ? {} : { runner: ctx.runner }),
    },
    { stdout: ctx.stdout, stderr: ctx.stderr },
  );
}

async function dispatchDetect(
  rest: string[],
  ctx: CliContext,
  json: boolean,
): Promise<number> {
  rejectUnknownOptions(rest, []);
  return runDetect(
    { cwd: ctx.cwd, json, platform: process.platform },
    { stdout: ctx.stdout, stderr: ctx.stderr },
  );
}

async function dispatchNormalize(
  rest: string[],
  ctx: CliContext,
  json: boolean,
): Promise<number> {
  rejectUnknownOptions(rest, ['--dry-run', '--fix']);
  return runNormalize(
    {
      cwd: ctx.cwd,
      dryRun: rest.includes('--dry-run'),
      fix: rest.includes('--fix'),
      json,
      platform: process.platform,
      ...(ctx.runner === undefined ? {} : { runner: ctx.runner }),
    },
    { stdout: ctx.stdout, stderr: ctx.stderr },
  );
}

function parseTargetProvider(value: string): TargetProvider {
  if (!(TARGET_PROVIDERS as readonly string[]).includes(value)) {
    throw new UsageError(`unknown target: ${value}`, 'usage.invalid-target', {
      hint: `Supported targets: ${TARGET_PROVIDERS.join(', ')}`,
    });
  }
  return value as TargetProvider;
}

async function dispatchPolicy(
  rest: string[],
  ctx: CliContext,
  json: boolean,
): Promise<number> {
  const [subcommand, ...args] = rest;
  if (subcommand !== 'explain') {
    throw new UsageError(
      'usage: dab policy explain [--agent <name>] [--target <provider>] [--json]',
      'usage.invalid-policy-command',
    );
  }
  rejectUnknownOptions(args, ['--agent', '--target']);
  const agent = takeOption(args, '--agent');
  const rawTarget = takeOption(args, '--target');
  const target = rawTarget === undefined ? undefined : parseTargetProvider(rawTarget);
  return runPolicyExplain(
    {
      cwd: ctx.cwd,
      ...(agent === undefined ? {} : { agent }),
      ...(target === undefined ? {} : { target }),
      json,
      platform: process.platform,
      ...(ctx.runner === undefined ? {} : { runner: ctx.runner }),
    },
    { stdout: ctx.stdout, stderr: ctx.stderr },
  );
}

async function dispatch(args: string[], ctx: CliContext, json: boolean): Promise<number> {
  const [command, ...rest] = args;
  if (command === undefined || command === '--help' || command === '-h' || command === 'help') {
    ctx.stdout(HELP);
    return ExitCode.Ok;
  }
  if (command === '--version' || command === '-v') {
    ctx.stdout(`${PROGRAM_VERSION}\n`);
    return ExitCode.Ok;
  }

  switch (command) {
    case 'init':
      return dispatchInit(rest, ctx, json);
    case 'detect':
      return dispatchDetect(rest, ctx, json);
    case 'normalize':
      return dispatchNormalize(rest, ctx, json);
    case 'policy':
      return dispatchPolicy(rest, ctx, json);
    default:
      throw new UsageError(
        `unknown command: ${command}`,
        'usage.unknown-command',
        { hint: 'Run "dab --help" to see available commands.' },
      );
  }
}

export async function runCli(argv: string[], ctx: CliContext): Promise<number> {
  const json = argv.includes('--json');
  const args = argv.filter((arg) => arg !== '--json');

  try {
    if (json && args.length === 0) {
      throw new UsageError('--json requires a command', 'usage.json-command');
    }
    const command = args[0];
    if (
      json
      && (command === '--help'
        || command === '-h'
        || command === 'help'
        || command === '--version'
        || command === '-v')
    ) {
      throw new UsageError(
        '--json cannot be combined with --help or --version',
        'usage.json-help',
      );
    }
    return await dispatch(args, ctx, json);
  } catch (error) {
    if (error instanceof DabError) {
      if (json) {
        ctx.stdout(contractJson({ ok: false, error: error.toJSON() }));
      } else {
        ctx.stderr(`dab: ${error.message}\n`);
        if (error.hint !== undefined) {
          ctx.stderr(`${error.hint}\n`);
        }
      }
      return error.exitCode;
    }

    const message = error instanceof Error ? error.message : String(error);
    if (json) {
      ctx.stdout(
        contractJson({
          ok: false,
          error: { code: 'internal.error', message, exitCode: ExitCode.Internal },
        }),
      );
    } else {
      ctx.stderr(`dab: internal error: ${message}\n`);
      if (ctx.env.DEBUG !== undefined && error instanceof Error && error.stack !== undefined) {
        ctx.stderr(`${error.stack}\n`);
      }
    }
    return ExitCode.Internal;
  }
}

function isMainModule(): boolean {
  const entry = process.argv[1];
  if (entry === undefined) {
    return false;
  }
  try {
    return realpathSync(entry) === fileURLToPath(import.meta.url);
  } catch {
    return false;
  }
}

if (isMainModule()) {
  void runCli(process.argv.slice(2), {
    cwd: process.cwd(),
    stdout: (value) => process.stdout.write(value),
    stderr: (value) => process.stderr.write(value),
    env: process.env,
  }).then((code) => {
    process.exitCode = code;
  });
}
