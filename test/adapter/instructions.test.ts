import { afterEach, describe, expect, it } from 'vitest';
import { mkdir, readFile, readlink, rm, symlink } from 'node:fs/promises';
import { join } from 'node:path';
import {
  applyInstructions,
  inspectInstructionTarget,
  planInstructions,
  renderClaudeMdShim,
} from '../../src/adapter/claude-code/instructions.ts';
import { lstatOrNull } from '../../src/core/fs-atomic.ts';
import { resolveProjectPaths } from '../../src/model/project-manifest.ts';
import type {
  GeneratedTarget,
  ProjectPaths,
} from '../../src/model/types.ts';
import { makeProject, writeProjectFile, type ProjectFixture } from '../helpers/project.ts';
import { makeTempDir } from '../helpers/tmp.ts';

const projects: ProjectFixture[] = [];
const dirs: string[] = [];

function projectPaths(root: string, scope: 'project' | 'global'): ProjectPaths {
  return resolveProjectPaths(root, {
    version: 2,
    scope,
    project: { id: 'demo', name: 'Demo' },
    profile: 'feature',
    targets: [{
      provider: 'claude-code',
      enabled: true,
      options: { minVersion: '2.1.277', instructions: 'symlink' },
    }],
    paths: { agents: '.agents', claude: '.claude' },
  });
}

function managed(mode: 'symlink' | 'generated' = 'symlink'): GeneratedTarget {
  return {
    provider: 'claude-code',
    settings: null,
    instructions: {
      path: '.claude/CLAUDE.md',
      mode,
      sha256: 'a'.repeat(64),
    },
    projections: [],
  };
}

async function project(): Promise<ProjectFixture> {
  const fixture = await makeProject();
  projects.push(fixture);
  await writeProjectFile(fixture.root, 'AGENTS.md', '# Project\n');
  return fixture;
}

async function home(): Promise<string> {
  const dir = await makeTempDir('dab-instructions-home-');
  dirs.push(dir);
  return dir;
}

afterEach(async () => {
  await Promise.all(projects.splice(0).map((item) => rm(item.root, { recursive: true, force: true })));
  await Promise.all(dirs.splice(0).map((dir) => rm(dir, { recursive: true, force: true })));
});

describe('renderClaudeMdShim', () => {
  it('renders the default and explicit import paths', () => {
    expect(renderClaudeMdShim()).toBe(
      '<!-- Generated by DAB from AGENTS.md. Do not edit. Run `dab normalize` to regenerate. -->\n@../AGENTS.md\n',
    );
    expect(renderClaudeMdShim('../.agents/AGENTS.md')).toBe(
      '<!-- Generated by DAB from AGENTS.md. Do not edit. Run `dab normalize` to regenerate. -->\n@../.agents/AGENTS.md\n',
    );
  });
});

describe('symlink instructions', () => {
  it('creates a project instruction symlink to AGENTS.md', async () => {
    const fixture = await project();
    const paths = projectPaths(fixture.root, 'project');

    const plan = await planInstructions({
      root: fixture.root,
      paths,
      mode: 'symlink',
    });
    await applyInstructions(fixture.root, plan);

    expect(plan.action).toBe('create');
    expect(await readlink(join(fixture.root, '.claude/CLAUDE.md'))).toBe('../AGENTS.md');
  });

  it('creates a global instruction symlink to .agents/AGENTS.md', async () => {
    const dir = await home();
    await mkdir(join(dir, '.agents'), { recursive: true });
    await writeProjectFile(dir, '.agents/AGENTS.md', '# Global\n');
    const paths = projectPaths(dir, 'global');

    const plan = await planInstructions({ root: dir, paths, mode: 'symlink' });
    await applyInstructions(dir, plan);

    expect(await readlink(join(dir, '.claude/CLAUDE.md'))).toBe('../.agents/AGENTS.md');
  });

  it('accepts a managed symlink and flags a broken one', async () => {
    const fixture = await project();
    const paths = projectPaths(fixture.root, 'project');
    const plan = await planInstructions({ root: fixture.root, paths, mode: 'symlink' });
    await applyInstructions(fixture.root, plan);

    expect(await planInstructions({ root: fixture.root, paths, mode: 'symlink' }))
      .toMatchObject({ action: 'none' });

    await rm(join(fixture.root, '.claude/CLAUDE.md'));
    await symlink('missing.md', join(fixture.root, '.claude/CLAUDE.md'));
    expect((await planInstructions({ root: fixture.root, paths, mode: 'symlink' })).conflict?.code)
      .toBe('claude-md.unmanaged');
  });

  it('backs up an unmanaged file only with fix', async () => {
    const fixture = await project();
    await writeProjectFile(fixture.root, '.claude/CLAUDE.md', 'user memory\n');
    const paths = projectPaths(fixture.root, 'project');

    const blocked = await planInstructions({ root: fixture.root, paths, mode: 'symlink' });
    expect(blocked.conflict?.code).toBe('claude-md.unmanaged');

    const fixed = await planInstructions({ root: fixture.root, paths, mode: 'symlink', fix: true });
    const backups = await applyInstructions(
      fixture.root,
      fixed,
      join(fixture.root, '.dab/backups/test'),
    );
    expect(backups.some((item) => item.endsWith('.claude/CLAUDE.md'))).toBe(true);
    expect(await readlink(join(fixture.root, '.claude/CLAUDE.md'))).toBe('../AGENTS.md');
  });

  it('repairs a drifted managed symlink without a backup', async () => {
    const fixture = await project();
    const paths = projectPaths(fixture.root, 'project');
    await mkdir(join(fixture.root, '.claude'), { recursive: true });
    await symlink('missing.md', join(fixture.root, '.claude/CLAUDE.md'));

    const plan = await planInstructions({
      root: fixture.root,
      paths,
      mode: 'symlink',
      generated: managed(),
    });
    const backups = await applyInstructions(fixture.root, plan);

    expect(plan).toMatchObject({ action: 'repair' });
    expect(backups).toEqual([]);
    expect(await readlink(join(fixture.root, '.claude/CLAUDE.md'))).toBe('../AGENTS.md');
  });

  it('repairs a managed generated shim into a symlink', async () => {
    const fixture = await project();
    const paths = projectPaths(fixture.root, 'project');
    await writeProjectFile(
      fixture.root,
      '.claude/CLAUDE.md',
      renderClaudeMdShim('../AGENTS.md'),
    );

    const plan = await planInstructions({
      root: fixture.root,
      paths,
      mode: 'symlink',
      generated: managed(),
    });
    await applyInstructions(fixture.root, plan);

    expect(plan).toMatchObject({ action: 'repair' });
    expect(await readlink(join(fixture.root, '.claude/CLAUDE.md'))).toBe('../AGENTS.md');
  });

  it('keeps a root CLAUDE.md conflict fatal even with fix', async () => {
    const fixture = await project();
    await writeProjectFile(fixture.root, 'CLAUDE.md', '# user instructions\n');
    const paths = projectPaths(fixture.root, 'project');

    const plan = await planInstructions({
      root: fixture.root,
      paths,
      mode: 'symlink',
      generated: managed(),
      fix: true,
    });

    expect(plan.action).toBe('none');
    expect(plan.conflict?.code).toBe('claude-md.unmanaged');
    expect(plan.conflict?.file).toBe('CLAUDE.md');
  });

  it('requires a backup root for backup actions', async () => {
    const fixture = await project();
    await writeProjectFile(fixture.root, '.claude/CLAUDE.md', 'user memory\n');
    const paths = projectPaths(fixture.root, 'project');
    const fixed = await planInstructions({ root: fixture.root, paths, mode: 'symlink', fix: true });

    await expect(applyInstructions(fixture.root, fixed)).rejects.toThrow(/backupRoot/);
  });
});

describe('missing instruction source', () => {
  it('plans no artifact when AGENTS.md is missing', async () => {
    const fixture = await project();
    await rm(join(fixture.root, 'AGENTS.md'));
    const paths = projectPaths(fixture.root, 'project');

    for (const mode of ['symlink', 'generated'] as const) {
      const plan = await planInstructions({ root: fixture.root, paths, mode });
      expect(plan).toMatchObject({ action: 'none' });
      expect(plan.conflict).toBeUndefined();
      expect(plan.sha256).toBeUndefined();
    }
  });

  it('removes a managed artifact when AGENTS.md disappears', async () => {
    const fixture = await project();
    const paths = projectPaths(fixture.root, 'project');
    const created = await planInstructions({ root: fixture.root, paths, mode: 'symlink' });
    await applyInstructions(fixture.root, created);
    await rm(join(fixture.root, 'AGENTS.md'));

    const plan = await planInstructions({
      root: fixture.root,
      paths,
      mode: 'symlink',
      generated: managed(),
    });
    expect(plan.action).toBe('remove');
    await applyInstructions(fixture.root, plan);
    expect(await lstatOrNull(join(fixture.root, '.claude/CLAUDE.md'))).toBeNull();
  });

  it('keeps an unmanaged target fatal even with fix when AGENTS.md is missing', async () => {
    const fixture = await project();
    await writeProjectFile(fixture.root, '.claude/CLAUDE.md', 'user memory\n');
    await rm(join(fixture.root, 'AGENTS.md'));
    const paths = projectPaths(fixture.root, 'project');

    const plan = await planInstructions({
      root: fixture.root,
      paths,
      mode: 'symlink',
      fix: true,
    });

    expect(plan.action).toBe('none');
    expect(plan.conflict?.code).toBe('claude-md.unmanaged');
    expect(await readFile(join(fixture.root, '.claude/CLAUDE.md'), 'utf8')).toBe('user memory\n');
  });
});

describe('generated instructions', () => {
  it('creates, accepts and repairs the gated shim according to ownership', async () => {
    const fixture = await project();
    const paths = projectPaths(fixture.root, 'project');

    const absent = await planInstructions({ root: fixture.root, paths, mode: 'generated' });
    expect(absent.action).toBe('create');
    await applyInstructions(fixture.root, absent);
    expect((await lstatOrNull(join(fixture.root, '.claude/CLAUDE.md')))?.isFile()).toBe(true);

    const accepted = await planInstructions({ root: fixture.root, paths, mode: 'generated' });
    expect(accepted.action).toBe('none');

    await writeProjectFile(fixture.root, '.claude/CLAUDE.md', 'drifted\n');
    const unmanaged = await planInstructions({ root: fixture.root, paths, mode: 'generated' });
    expect(unmanaged.conflict?.code).toBe('claude-md.unmanaged');

    const repaired = await planInstructions({
      root: fixture.root,
      paths,
      mode: 'generated',
      generated: managed('generated'),
    });
    await applyInstructions(fixture.root, repaired);
    expect(repaired.action).toBe('repair');
    expect(await readProjectShim(fixture.root)).toBe(renderClaudeMdShim('../AGENTS.md'));
  });

  it('uses the global relative import in generated mode', async () => {
    const dir = await home();
    await mkdir(join(dir, '.agents'), { recursive: true });
    await writeProjectFile(dir, '.agents/AGENTS.md', '# Global\n');
    const paths = projectPaths(dir, 'global');

    const plan = await planInstructions({ root: dir, paths, mode: 'generated' });
    await applyInstructions(dir, plan);

    expect(await readProjectShim(dir)).toBe(renderClaudeMdShim('../.agents/AGENTS.md'));
  });
});

describe('disabled instructions', () => {
  it('removes a managed target and blocks an unmanaged one', async () => {
    const fixture = await project();
    const paths = projectPaths(fixture.root, 'project');
    await writeProjectFile(fixture.root, '.claude/CLAUDE.md', 'user memory\n');

    const blocked = await planInstructions({ root: fixture.root, paths, mode: 'disabled' });
    expect(blocked.action).toBe('none');
    expect(blocked.conflict?.code).toBe('claude-md.unmanaged');

    const managedPlan = await planInstructions({
      root: fixture.root,
      paths,
      mode: 'disabled',
      generated: managed(),
    });
    expect(managedPlan.action).toBe('remove');
    await applyInstructions(fixture.root, managedPlan);
    expect(await lstatOrNull(join(fixture.root, '.claude/CLAUDE.md'))).toBeNull();
  });

  it('backs up an unmanaged target only with fix', async () => {
    const fixture = await project();
    const paths = projectPaths(fixture.root, 'project');
    await writeProjectFile(fixture.root, '.claude/CLAUDE.md', 'user memory\n');

    const fixed = await planInstructions({ root: fixture.root, paths, mode: 'disabled', fix: true });
    expect(fixed.action).toBe('backup-and-remove');
    const backups = await applyInstructions(
      fixture.root,
      fixed,
      join(fixture.root, '.dab/backups/test'),
    );
    expect(backups.some((item) => item.endsWith('.claude/CLAUDE.md'))).toBe(true);
    expect(await lstatOrNull(join(fixture.root, '.claude/CLAUDE.md'))).toBeNull();
  });
});

describe('inspectInstructionTarget', () => {
  it('accepts absent, managed and expected targets', async () => {
    const fixture = await project();
    const paths = projectPaths(fixture.root, 'project');

    expect(await inspectInstructionTarget(fixture.root, paths, 'symlink')).toBeUndefined();

    const plan = await planInstructions({ root: fixture.root, paths, mode: 'symlink' });
    await applyInstructions(fixture.root, plan);
    expect(await inspectInstructionTarget(fixture.root, paths, 'symlink')).toBeUndefined();
    expect(await inspectInstructionTarget(fixture.root, paths, 'symlink', managed()))
      .toBeUndefined();

    await writeProjectFile(fixture.root, '.claude/CLAUDE.md', renderClaudeMdShim('../AGENTS.md'));
    expect(await inspectInstructionTarget(fixture.root, paths, 'generated')).toBeUndefined();
  });

  it('reports an unmanaged target', async () => {
    const fixture = await project();
    await writeProjectFile(fixture.root, '.claude/CLAUDE.md', 'user memory\n');
    const paths = projectPaths(fixture.root, 'project');

    const diagnostic = await inspectInstructionTarget(fixture.root, paths, 'symlink');
    expect(diagnostic?.code).toBe('claude-md.unmanaged');
    expect(diagnostic?.file).toBe('.claude/CLAUDE.md');
  });
});

async function readProjectShim(root: string): Promise<string> {
  return readFile(join(root, '.claude/CLAUDE.md'), 'utf8');
}
